from PIL import Image, ImageDraw
W, H = 600, 650
im = Image.new("L", (W, H), 255); d = ImageDraw.Draw(im)
cx, cy = 300, 405
for dx, rx, ry in ((-120, 130, 195), (120, 130, 195), (-60, 145, 215), (60, 145, 215), (0, 140, 220)):
    d.ellipse([cx+dx-rx, cy-ry, cx+dx+rx, cy+ry], fill=0)
d.polygon([(272, 200), (328, 200), (332, 95), (365, 0), (318, 0), (285, 90)], fill=0)   # stem
d.polygon([(165, 365), (265, 365), (215, 265)], fill=255)    # eyes
d.polygon([(335, 365), (435, 365), (385, 265)], fill=255)
d.polygon([(268, 435), (332, 435), (300, 385)], fill=255)    # nose
top = [(140, 465), (190, 485), (210, 515), (240, 492), (270, 500), (300, 480),
       (330, 500), (360, 492), (390, 515), (410, 485), (460, 465)]
bot = [(435, 545), (395, 585), (360, 560), (330, 595), (300, 575), (270, 595),
       (240, 560), (205, 585), (165, 545)]
d.polygon(top + bot, fill=255)                                # grin
im.save("jack.png")
